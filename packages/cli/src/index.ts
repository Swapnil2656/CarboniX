    console.log(pc.green('  │') + `  Project  : ${pc.white(projectName.substring(0, 37).padEnd(39))}` + pc.green('│'));
    console.log(pc.green('  ├─────────────────────────────────────────────────────┤'));
    console.log(pc.green('  │') + pc.gray('  ✅  .carbonixrc                                     ') + pc.green('│'));
