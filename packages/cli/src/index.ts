appCmd
  .command('deploy')
  .description('Deploy and send telemetry to CarboniX with AI-powered carbon optimization')
  .option('-p, --project <project>', 'Target project name')
  .action(async (options) => {
    const config = await readConfig();
    const baseUrl = config.baseUrl || DEFAULT_API_BASE;

    let projectName = options.project || config.projectName;
    if (!projectName) {
      try {
        const pkgData = await fs.readFile(path.join(process.cwd(), 'package.json'), 'utf-8');
        projectName = JSON.parse(pkgData).name;
      } catch {
        projectName = 'unknown-project';
      }
    }

    console.log('');
    console.log(pc.cyan(`  📦 Deploying: ${projectName}`));
    console.log('');

    let currentRegion   = config.region   || 'us-east-1';
    let currentProvider = config.provider || 'aws';

    const baseTelemetry: any = {
      projectName,
      instanceType: 't3.medium',
      provider: currentProvider,
      region: currentRegion,
      cpuUtilization: Math.random() * 0.4 + 0.1,
      storageGb: 20,
    };

    // AI region optimization
    process.stdout.write(pc.gray('  [1/2] AI region optimization... '));
    try {
      const recRes = await axios.post(`${baseUrl}/api/v1/carbon/recommend`, baseTelemetry, {
        headers: { 'Authorization': `Bearer ${config.apiKey}`, 'Content-Type': 'application/json' },
        timeout: 10000,
      });

      if (recRes.data.success && recRes.data.data.recommended) {
        const rec = recRes.data.data.recommended;
        if (rec.reductionPercent > 10 && rec.region !== currentRegion) {
          console.log(pc.green(`switching region`));
          console.log(pc.green(`     ${currentRegion} → ${rec.region} (~${Math.round(rec.reductionPercent)}% less carbon)`));
          currentRegion = rec.region;
          baseTelemetry.region = currentRegion;

          // Rewrite vercel.json if present
          if (currentProvider.toLowerCase() === 'vercel') {
            try {
              const vercelConfigPath = path.join(process.cwd(), 'vercel.json');
              const vercelData = await fs.readFile(vercelConfigPath, 'utf-8');
              const vercelJson = JSON.parse(vercelData);
              if (vercelJson.regions && Array.isArray(vercelJson.regions)) {
                vercelJson.regions = [rec.region];
                await fs.writeFile(vercelConfigPath, JSON.stringify(vercelJson, null, 2));
                console.log(pc.yellow(`     📝 Updated vercel.json → region: ${rec.region}`));
              }
            } catch (_) {}
          }
        } else {
          console.log(pc.green('already optimal'));
        }
      } else {
        console.log(pc.gray('skipped'));
      }
    } catch {
      console.log(pc.gray('unavailable — using default region'));
    }

    // Send telemetry
    process.stdout.write(pc.gray('  [2/2] Uploading telemetry... '));
    try {
      const res = await axios.post(`${baseUrl}/api/v1/carbon/telemetry/ingest`, baseTelemetry, {
        headers: { 'Authorization': `Bearer ${config.apiKey}`, 'Content-Type': 'application/json' },
        timeout: 10000,
      });
      if (res.data.success) {
        console.log(pc.green('✅ Done'));
        console.log('');
        console.log(pc.green(`  🚀 Deployment recorded!`));
        console.log(pc.gray(`  Carbon: ${res.data.data?.carbonKg?.toFixed(4)} kg CO₂e`));
        console.log(pc.gray(`  Region: ${currentRegion} | Provider: ${currentProvider.toUpperCase()}`));
      } else {
        console.log(pc.red('❌ Failed'));
      }
    } catch (err: any) {
      console.log(pc.red('❌ Error'));
      console.error(pc.red(`  ${err.response?.data?.error || err.message}`));
    }
    console.log('');
  });

