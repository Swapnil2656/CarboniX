const TELEMETRY_JS_CONTENT = `/**
 * CarboniX Telemetry Reporter
 * Generated by: npx @carbonix/cli init
 * ─────────────────────────────────────────────────────────────────────────────
 * Reports live CPU metrics to your CarboniX Dashboard every 5 minutes.
 * The AI Analyst flags idle/oversized instances and suggests savings.
 */
const os = require('os');
const { cx } = require('./carbonix.config');

function getCpuUtilization() {
  return new Promise(resolve => {
    const t1 = os.cpus();
    setTimeout(() => {
      const t2 = os.cpus();
      let idle = 0, total = 0;
      t1.forEach((cpu, i) => {
        for (const type in t2[i].times) total += t2[i].times[type] - cpu.times[type];
        idle += t2[i].times.idle - cpu.times.idle;
      });
      resolve(parseFloat((1 - idle / total).toFixed(4)));
    }, 100);
  });
}

function startTelemetry({ instanceId, instanceType, provider, region, projectName, intervalMs = 5 * 60 * 1000, storageGb = 0 }) {
  const report = async () => {
    try {
      const cpuUtilization = await getCpuUtilization();
      const record = await cx.ingest({ instanceId, instanceType, provider, region, cpuUtilization, storageGb, projectName });
      console.log(\`[CarboniX] 📊 \${record.carbonKg.toFixed(4)} kg CO₂ | CPU: \${(cpuUtilization * 100).toFixed(1)}% | idle: \${record.isIdle}\`);
    } catch (err) {
      console.warn('[CarboniX] Telemetry failed (non-fatal):', err.message);
    }
  };
  report();
  const timer = setInterval(report, intervalMs);
  if (timer.unref) timer.unref();
  console.log(\`[CarboniX] ✅ Reporting every \${intervalMs / 1000}s for \${instanceId}\`);
  return { stop: () => clearInterval(timer) };
}

module.exports = { startTelemetry };
`;

// ─── Helpers ──────────────────────────────────────────────────────────────────

const ENTRY_FILE_CANDIDATES = [
  'server.js', 'server.ts', 'index.js', 'index.ts', 'app.js', 'app.ts',
  'src/server.js', 'src/server.ts', 'src/index.js', 'src/index.ts',
  'src/app.js', 'src/app.ts', 'main.js', 'main.ts',
];

async function detectEntryFile(cwd: string): Promise<string | null> {
  try {
    const pkg = JSON.parse(await fs.readFile(path.join(cwd, 'package.json'), 'utf-8'));
    if (pkg.main && await fileExists(path.join(cwd, pkg.main))) return pkg.main;
  } catch (_) {}
  for (const c of ENTRY_FILE_CANDIDATES) {
    if (await fileExists(path.join(cwd, c))) return c;
  }
  return null;
}

async function fileExists(p: string): Promise<boolean> {
  try { await fs.access(p); return true; } catch { return false; }
}

async function detectEnvVars(cwd: string): Promise<Record<string, string>> {
  const vars: Record<string, string> = {};
  for (const envFile of ['.env', '.env.local', '.env.production']) {
    try {
      const lines = (await fs.readFile(path.join(cwd, envFile), 'utf-8')).split('\n');
      for (const line of lines) {
        const m = line.match(/^([^#=]+)=(.*)$/);
        if (m) vars[m[1].trim()] = m[2].trim().replace(/^["']|["']$/g, '');
      }
    } catch (_) {}
  }
  return vars;
}

async function readConfig(): Promise<any> {
  try {
    const data = await fs.readFile(CONFIG_PATH, 'utf-8');
    return JSON.parse(data);
  } catch {
    console.error(pc.red('\n  ❌  Not initialized. Run:') + pc.white('  npx @carbonix/cli init --key <your-api-key>\n'));
    process.exit(1);
  }
}

function detectProvider(envVars: Record<string, string>): string {
  if (process.env.VERCEL               || envVars.VERCEL)               return 'vercel';
  if (process.env.NETLIFY              || envVars.NETLIFY)               return 'netlify';
  if (process.env.RAILWAY_ENVIRONMENT  || envVars.RAILWAY_ENVIRONMENT)   return 'railway';
  if (process.env.RENDER               || envVars.RENDER)                return 'render';
  if (process.env.GOOGLE_CLOUD_PROJECT || envVars.GOOGLE_CLOUD_PROJECT)  return 'gcp';
  if (process.env.ARM_REGION           || envVars.ARM_REGION || process.env.AZURE_REGION || envVars.AZURE_REGION) return 'azure';
  return 'aws';
}

function buildInjectionSnippet(cfg: Record<string, string>): string {
  return [
    '',
    '// ─── CarboniX Auto-injected by @carbonix/cli (do not remove) ──────────────',
    "const { startTelemetry } = require('./carbonix-telemetry');",
    'startTelemetry({',
    `  instanceId:   process.env.INSTANCE_ID    || '${cfg.instanceId}',`,
    `  instanceType: process.env.INSTANCE_TYPE  || '${cfg.instanceType}',`,
    `  provider:     process.env.CLOUD_PROVIDER || '${cfg.provider}',`,
    `  region:       process.env.AWS_REGION     || '${cfg.region}',`,
    `  projectName:  process.env.APP_NAME       || '${cfg.projectName}',`,
    '});',
    '// ───────────────────────────────────────────────────────────────────────────',
    '',
  ].join('\n');
}

